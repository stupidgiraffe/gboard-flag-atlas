import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFileSync,existsSync,readdirSync} from 'node:fs';
import {join} from 'node:path';
const root=process.cwd(),out='/tmp/gfa-seo-test-output';
execFileSync(process.execPath,[join(root,'scripts/build-site.mjs'),out],{stdio:'pipe'});
const read=p=>readFileSync(join(out,p),'utf8');
const flags=JSON.parse(read('data/flags.json')).entries;
assert.equal(flags.length,691);
const indexable=flags.filter(f=>['Code-referenced','Community-referenced','Library-referenced','Interpreted'].includes(f.confidence));
assert.equal(indexable.length,158);
assert.equal(readdirSync(join(out,'flags')).length,158);
const xml=read('sitemap.xml');
assert.equal((xml.match(/<loc>/g)||[]).length,169);
assert.ok(xml.includes('/flags/enable_ac_threshold/'));
assert.ok(!xml.includes('/flags/use_4c_in_signboard/'));
assert.ok(read('robots.txt').includes('Sitemap: https://gboard-flag-atlas.shipstatic.com/sitemap.xml'));
const home=read('index.html');
assert.ok(home.includes('Privacy-friendly analytics.'));
assert.ok(home.includes('var permalink=mk('));
assert.ok(home.includes('class="topiclinks"'));
assert.ok(home.includes('No login. Privacy-friendly analytics.'));
assert.ok(!home.includes('No login. No tracking.'));
assert.equal((home.match(/static.cloudflareinsights.com\/beacon.min.js/g)||[]).length,1);
const detail=read('flags/enable_ac_threshold/index.html');
assert.ok(detail.includes('Enables an autocorrection confidence threshold'));
assert.ok(detail.includes('rel="canonical"'));
assert.ok(detail.includes('https://gboard-flag-atlas.shipstatic.com/flags/enable_ac_threshold/'));
assert.ok(detail.includes('Google Gboard research'));
assert.equal((detail.match(/static.cloudflareinsights.com\/beacon.min.js/g)||[]).length,1);
assert.ok(read('topics/predictions-and-corrections/index.html').includes('enable_ac_threshold'));
assert.equal(readdirSync(join(out,'topics')).length,10);
assert.ok(!existsSync(join(out,'flags/use_4c_in_signboard/index.html')));
console.log('Static SEO and analytics build: 17 assertions passed.');
