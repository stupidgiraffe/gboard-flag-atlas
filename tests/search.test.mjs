import assert from 'node:assert/strict';
import fs from 'node:fs';
import Fuse from '../fuse.min.mjs';
import {createFlagSearch} from '../flag-search.mjs';
const data=JSON.parse(fs.readFileSync(new URL('../flags.json', import.meta.url),'utf8'));
const find=createFlagSearch(data.entries,Fuse);
const names=(q)=>find(q).map(e=>e.name);
assert.equal(data.entries.length,691);
assert.equal(names('AC')[0],'enable_ac_threshold');
assert.ok(names('AC').includes('pref_key_latin_enable_ac_revert'));
assert.ok(names('AC').length<15,'AC must not trigger incidental substring matches');
assert.ok(!names('AC').includes('disable_at_the_cursor_feature'));
assert.ok(!names('AC').includes('enable_access_points_menu_redesign'));
assert.equal(names('enable_ac_threshold')[0],'enable_ac_threshold');
assert.equal(names('KC')[0],'enable_kc_threshold');
assert.ok(names('autocorect').includes('pref_key_auto_correction'));
assert.ok(names('emoji kitcen').includes('enable_emoji_kitchen_scaling'));
assert.ok(names('emoji kitchen').includes('enable_emoji_kitchen_scaling'));
assert.ok(names('access').includes('enable_access_points_menu_redesign'));
assert.ok(names('gemma').some(n=>n.includes('gemma')));
assert.ok(names('gif').some(n=>n.includes('gif')));
assert.deepEqual(names('ac'),names('AC'),'case insensitive');
assert.equal(names('notexistentialqueryzz').length,0);
assert.equal(names('  ').length,data.entries.length);
console.log('16 ranked-search assertions passed');
